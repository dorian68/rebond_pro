import "./_env";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { prisma } from "../src/lib/prisma";
import { createTestTenant, step, assert } from "./_tenant";
import { hashPassword } from "../src/lib/password";
import { questions, type Answers } from "../src/features/questionnaire/schema";

const base = process.env.SMOKE_BASE_URL ?? "http://localhost:3105";
if (!['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw new Error("Cette recette exige un environnement local isolé.");

async function main() {
  mkdirSync('.run/questionnaire', { recursive: true });
  const tenant = await createTestTenant('questionnaire-ui');
  const ordinary = await createTestTenant('questionnaire-nonadmin');
  const password = `Synthetic-${randomUUID()}!`;
  const fixtureName = `Recette synthétique ${randomUUID().slice(0,8)}`;
  const submissionKeys: string[] = [];
  const browser = await chromium.launch({ headless: true });
  let complete = false;
  try {
    const hash = await hashPassword(password);
    await prisma.user.update({ where: { id: tenant.userId }, data: { platformAdmin: true, emailVerified: new Date(), passwordHash: hash } });
    await prisma.user.update({ where: { id: ordinary.userId }, data: { emailVerified: new Date(), passwordHash: hash } });
    const context = await browser.newContext({ baseURL: base, viewport: { width: 1365, height: 1000 } });
    const page = await context.newPage();
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto('/questionnaire');
    await expect(page.getByRole('heading', { name: 'Votre prochaine étape professionnelle' })).toBeVisible();
    await expect(page.getByRole('link', { name: 'Questionnaires', exact: true })).toHaveCount(0);
    await page.getByLabel('Sans emploi depuis moins de 6 mois', { exact: true }).check();
    await page.getByLabel('Créer ou reprendre une activité à mon compte', { exact: true }).check();
    await page.getByLabel('Commerce, vente, accueil', { exact: true }).check();
    await page.getByLabel('Métier ou autre domaine', { exact: false }).fill('Activité synthétique de services');
    await page.getByLabel('Un emploi stable', { exact: true }).check();
    await page.getByLabel('Comprendre le marché de l’emploi', { exact: true }).check();
    await page.getByLabel('Faire avancer mon projet d’activité', { exact: true }).check();
    await page.screenshot({ path: '.run/questionnaire/public-desktop.png', fullPage: true });
    const axe = await new AxeBuilder({ page }).analyze();
    assert(axe.violations.length === 0, 'Accessibilité publique: '+axe.violations.map(v => v.id).join(','));
    await page.getByRole('button', { name: 'Continuer' }).click();
    await page.getByRole('button', { name: 'Précédent' }).click();
    await expect(page.getByLabel('Créer ou reprendre une activité à mon compte', { exact: true })).toBeChecked();
    await page.getByRole('button', { name: 'Continuer' }).click();
    await page.getByLabel('Dès maintenant', { exact: true }).check();
    await page.getByRole('button', { name: 'Continuer' }).click();
    await page.getByLabel('Non', { exact: true }).check();
    await page.getByLabel('Aucune pour le moment', { exact: true }).check();
    await page.getByLabel('J’accepte que mes réponses', { exact: false }).check();
    await page.getByLabel('Oui, par téléphone', { exact: true }).check();
    await page.getByRole('textbox', { name: 'Téléphone', exact: true }).fill('123');
    await page.getByRole('button', { name: 'Demander un échange', exact: true }).click();
    await expect(page.getByText('Saisissez un numéro de téléphone valide.', { exact: true })).toBeVisible();
    await page.getByLabel('Oui, par email', { exact: true }).check();
    await expect(page.getByText('Saisissez un numéro de téléphone valide.', { exact: true })).toHaveCount(0);
    await page.getByRole('textbox', { name: 'Adresse email', exact: true }).fill('synthetic@example.test');
    await page.getByLabel('Non, pas pour le moment', { exact: true }).check();
    await expect(page.getByRole('textbox', { name: 'Téléphone', exact: true })).toHaveCount(0);
    await page.getByLabel('J’accepte que mes réponses', { exact: false }).check();
    let sentKey = '';
    page.on('request', request => { if (request.url().endsWith('/api/questionnaire') && request.method() === 'POST') { const d = request.postDataJSON(); if (d?.submissionKey) { sentKey=d.submissionKey; submissionKeys.push(sentKey); } } });
    await page.route('**/api/questionnaire', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'La demande n’est pas confirmée. Réessayez.' }) }), { times: 1 });
    await page.getByRole('button', { name: 'Terminer', exact: true }).click();
    await expect(page.getByRole('alert').filter({ hasText: 'Réessayez' })).toBeVisible();
    assert(await prisma.questionnaireResponse.count({ where: { submissionKey: sentKey } }) === 0,'Pas de réponse créée lors de la panne simulée');
    await page.getByRole('button', { name: 'Terminer', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Vos réponses ont bien été enregistrées' })).toBeVisible();
    const saved = await prisma.questionnaireResponse.findUniqueOrThrow({ where: { submissionKey: sentKey } });
    assert(!saved.phone && !saved.email && !saved.firstName,'Aucune coordonnée recueillie sans rappel');
    step('public_journey_retry_persistence_no_contact');

    const response = await context.request.get('/api/admin/questionnaires');
    assert(response.status()===403,'Liste protégée sans connexion');
    assert((await context.request.get(`/api/admin/questionnaires/${saved.id}`)).status()===403,'Détail protégé');
    assert((await context.request.get('/api/admin/questionnaires?format=csv')).status()===403,'Export protégé');
    const answers: Answers={}; for(const q of questions)if(q.required)answers[q.id]=q.type==='multiple'?[q.options![0]]:q.options![0];
    answers.rappel='Oui, par email';
    const key=randomUUID(); submissionKeys.push(key);
    const payload={submissionKey:key,answers,consent:true,email:'synthetic@example.test',firstName:fixtureName,sectorDetail:'=1+1'};
    const apiHeaders={Origin:base,'Content-Type':'application/json'};
    assert((await context.request.post('/api/questionnaire',{headers:{...apiHeaders,Origin:'https://example.invalid'},data:payload})).status()===403,'Origine externe refusée');
    assert((await context.request.post('/api/questionnaire',{headers:{...apiHeaders,Origin:'%%%INVALID'},data:payload})).status()===403,'Origine invalide refusée');
    assert((await context.request.post('/api/questionnaire',{headers:apiHeaders,data:payload})).status()===200,'Email transmis et sauvegardé');
    assert((await context.request.post('/api/questionnaire',{headers:apiHeaders,data:payload})).status()===200,'Rejeu HTTP sûr');
    assert(await prisma.questionnaireResponse.count({where:{submissionKey:key}})===1,'Une ligne après rejeu HTTP');
    const emailRow=await prisma.questionnaireResponse.findUniqueOrThrow({where:{submissionKey:key}});
    assert(emailRow.email==='synthetic@example.test'&&!emailRow.phone,'Un seul canal enregistré');
    step('public_http_origin_idempotency_email');

    await page.goto('/login?space=admin&next=/admin/questionnaires');
    await page.locator('#email').fill(tenant.email!); await page.locator('#password').fill(password);
    await page.locator('button[type="submit"]').click();
    await page.waitForURL('**/admin/questionnaires', { timeout: 45_000 });
    await expect(page.getByRole('heading',{name:'Questionnaires',exact:true})).toBeVisible({timeout:30_000});
    await expect(page.getByRole('cell',{name:fixtureName,exact:true})).toBeVisible();
    await page.screenshot({path:'.run/questionnaire/admin-responses.png',fullPage:true});
    await page.getByRole('row').filter({hasText:fixtureName}).getByRole('button',{name:/Voir/}).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await expect(page.getByRole('dialog')).toContainText('synthetic@example.test');
    await page.getByRole('dialog').getByLabel('Statut').selectOption('IN_PROGRESS');
    await expect(page.getByRole('dialog').getByRole('status')).toContainText('enregistré');
    await page.screenshot({path:'.run/questionnaire/admin-detail.png',fullPage:true});
    await page.getByRole('button',{name:'Fermer',exact:true}).click(); await page.reload();
    await expect(page.getByRole('row').filter({hasText:fixtureName})).toContainText('En cours');
    const csv=await context.request.get('/api/admin/questionnaires?format=csv');
    assert(csv.status()===200&&(await csv.text()).includes("'=1+1"),'CSV avec protection contre les formules');
    await page.getByRole('button',{name:'Statistiques',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Quelle est votre priorité ?'})).toBeVisible();
    await page.screenshot({path:'.run/questionnaire/admin-statistics.png',fullPage:true});
    const adminAxe=await new AxeBuilder({page}).analyze();
    assert(adminAxe.violations.length===0,'Accessibilité admin: '+adminAxe.violations.map(v=>v.id).join(','));
    await context.storageState({path:'.run/questionnaire/admin-state.json'});
    writeFileSync('.run/questionnaire/review-fixture.json',JSON.stringify({adminEmail:tenant.email,password,responseId:emailRow.id,organizationId:tenant.organizationId,userId:tenant.userId,ordinaryUserId:ordinary.userId,ordinaryOrganizationId:ordinary.organizationId,submissionKeys}));
    step('admin_detail_statistics_csv_and_status_persistence');

    const other=await browser.newContext({baseURL:base}); const otherPage=await other.newPage();
    await otherPage.goto('/login?space=centre'); await otherPage.locator('#email').fill(ordinary.email!); await otherPage.locator('#password').fill(password); await otherPage.locator('button[type="submit"]').click();
    await otherPage.waitForURL(/\/(dashboard|onboarding)(?:[/?]|$)/,{timeout:45_000});
    assert((await other.request.get('/api/admin/questionnaires')).status()===403,'Admin centre refusé');
    assert((await other.request.delete(`/api/admin/questionnaires/${emailRow.id}`,{headers:{Origin:base}})).status()===403,'Suppression refusée admin centre');
    step('ordinary_tenant_access_denied'); await other.close();
    const mobile=await browser.newContext({baseURL:base,viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1}); const mobilePage=await mobile.newPage(); await mobilePage.goto('/questionnaire');
    assert(await mobilePage.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Pas de débordement horizontal mobile');
    await mobilePage.screenshot({path:'.run/questionnaire/public-mobile.png',fullPage:true});
    const mobileAxe=await new AxeBuilder({page:mobilePage}).analyze(); assert(!mobileAxe.violations.length,'Axe mobile'); await mobile.close();
    const headerSource=readFileSync('src/components/site/Header.tsx','utf8'); assert(!headerSource.includes('/questionnaire'),'Aucun lien dans la navbar publique');
    assert(errors.length===0,'Pas d’erreur JavaScript: '+errors.join(';'));
    step('mobile_accessibility_and_no_public_nav_link');
    complete = true;
  } finally {
    if(!complete || process.env.KEEP_QUESTIONNAIRE_FIXTURE!=='true') {
      await prisma.questionnaireResponse.deleteMany({where:{submissionKey:{in:submissionKeys}}}); await tenant.cleanup(); await ordinary.cleanup();
    }
    await browser.close(); await prisma.$disconnect();
  }
}
main().catch(error=>{console.error(JSON.stringify({status:'fail',error:error.message}));process.exitCode=1;});
